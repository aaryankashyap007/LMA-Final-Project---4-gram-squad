"""Evaluate the red-flag tagger and the script detector against D3.

Run from repo root:  python scripts/eval_tagger.py [--out docs/TAGGER_EVAL.md]

Ground truth for tags is DERIVED: each case's cue list (written by the annotators, e.g. "blue_lips", "no_chest_pain")
is mapped to red-flag tags by the regex rules below. Cues starting with "no_" are negations and never produce a tag.
This is a proxy, not clinician-labelled truth: the rules were written by the same team that wrote the cues, and the
tagger lexicon was written after looking at the cue vocabulary, so the numbers are optimistic. Report them as
agreement with cue-derived tags, never as clinical accuracy. Intents have no labelled data and are not scored here.
Script detection is scored against D3's own script labels (en / deva / hinglish).
"""
import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from swasthya import kio  # noqa: E402
from swasthya.normaliser import detect_script  # noqa: E402
from swasthya.tags import RED_FLAGS, red_flags  # noqa: E402

CUE_RULES = {
    "breathing_difficulty": r"breath|gasp|suffocat|chok|blue_lips|blue_skin|purple|throat_closing|asthma_attack",
    "unresponsive_or_collapse": r"unrespons|unconscious|unarous|not_waking|collapse|faint|losing_consciousness|"
                                r"barely_conscious|blackout|passed_out",
    "seizure": r"seizure|convuls|froth|(^|_)fits",
    "severe_bleeding": r"heavy_.*bleeding|spurting|active_bleeding|bleeding_not|not_stopping|blood_loss|vomiting_blood",
    "poisoning_overdose": r"overdose|poison|swallowed|ingest|pesticide|kerosene|acid|sleeping_pills|battery|"
                          r"floor_cleaner",
    "chest_pain_cardiac": r"chest_(pain|pressure|tight|discomfort|squeez)|crushing|radiating|pain_left_arm|"
                          r"stabbing_chest|tearing_to_back|sharp_chest",
    "stroke_signs": r"stroke|face_drooping|facial_asymmetry|slurred|speech|cannot_speak|paralysis|weakness_(left|right)|"
                    r"(left|right)_side_weak|arm_drift|sudden_blind|double_vision|thunderclap|sudden_confusion|"
                    r"right_arm_weakness|sudden_leg_weakness",
    "suicidal_intent": r"suicid|has_plan|cannot_take_it_anymore|hurt_myself|harm_myself",
    "pregnancy_danger": r"vaginal_bleeding|baby_head|labou?r|water_broke|not_moving|fetal",
    "dehydration_or_lethargy": r"not_drinking|not_feeding|not_passing_urine|no_urine|(^|_)limp$|floppy|very_sleepy|"
                               r"very_drowsy|hard_to_wake|dark_urine|dehydrat",
    "head_injury_trauma": r"head_injury|head_hit|fall_from|road_traffic_accident|spinal|cannot_feel_legs|scalp",
    "burn_or_deep_wound": r"burn|deep_cut|stab|severed|laceration|chemical_splash|acid|neck_cut|skin_tear|compound",
    "animal_bite_or_sting": r"snake|scorpion|bee_sting|multiple_bee|dog_bite|monkey|stray_dog|(^|_)bite",
    "allergic_reaction": r"allergic|swollen_tongue|throat_closing|hives|face_swelling",
}
SKIP = re.compile(r"^no_|mild|known|history|checkup|follow_up|exertion|exercise|stairs|brief|resolved|recovered|stable")
PREG_CUE = re.compile(r"pregnan|months$|^\d+months")


def cue_tags(cues):
    tags = set()
    for c in cues:
        if SKIP.search(c):
            continue
        tags |= {t for t, rx in CUE_RULES.items() if re.search(rx, c)}
    if any(PREG_CUE.search(c) for c in cues) and tags & {"severe_bleeding", "seizure"}:
        tags.add("pregnancy_danger")
    return tags


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/TAGGER_EVAL.md")
    a = ap.parse_args()
    L = ["# Tagger and script-detector evaluation", "",
         "Generated by `scripts/eval_tagger.py`. Tag truth is DERIVED from D3 cue lists (see the script header): "
         "an optimistic proxy, not clinician labels. Intents are not scored (no labelled data).", ""]
    for split in ("train", "dev", "test"):
        rows = kio.read_jsonl(ROOT / f"data/d3_triage/rendered/d3_{split}.jsonl")
        tp, fp, fn = Counter(), Counter(), Counter()
        any_flag = defaultdict(lambda: [0, 0])
        script_ok, script_conf = 0, Counter()
        for r in rows:
            pred, truth = set(red_flags(r["text"])), cue_tags(r["cues"])
            for t in RED_FLAGS:
                tp[t] += t in pred and t in truth
                fp[t] += t in pred and t not in truth
                fn[t] += t not in pred and t in truth
            any_flag[r["label"]][0] += bool(pred)
            any_flag[r["label"]][1] += 1
            s = detect_script(r["text"])
            script_ok += s == r["script"]
            if s != r["script"]:
                script_conf[(r["script"], s)] += 1
        L += [f"## {split} ({len(rows)} renderings)", "", "| tag | support | precision | recall |", "|---|---|---|---|"]
        for t in RED_FLAGS:
            sup, pp = tp[t] + fn[t], tp[t] + fp[t]
            L.append(f"| {t} | {sup} | {tp[t] / pp:.2f} |" if pp else f"| {t} | {sup} | n/a |")
            L[-1] += f" {tp[t] / sup:.2f} |" if sup else " n/a |"
        L += ["", "Share of renderings with at least one tag, by gold urgency label "
              "(a sound tagger flags most EMERGENCY and few ROUTINE):", ""]
        L += [f"- {lab}: {k}/{n} = {k / n:.2f}" for lab, (k, n) in sorted(any_flag.items())]
        L += ["", f"Script detection: {script_ok}/{len(rows)} = {script_ok / len(rows):.3f}; "
              f"errors by (true, detected): {dict(script_conf) or 'none'}", ""]
    out = ROOT / a.out
    out.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    print(f"\nsaved {a.out}")


if __name__ == "__main__":
    main()
